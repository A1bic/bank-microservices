CREATE TABLE roles
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         VARCHAR(64)  NOT NULL UNIQUE,
    name          VARCHAR(255) NOT NULL,
    age           INTEGER      NOT NULL,
    gender        VARCHAR(16)  NOT NULL,
    hair_color    VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role_id       BIGINT       NOT NULL REFERENCES roles (id)
);

CREATE TABLE user_friends
(
    user_id   BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    friend_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, friend_id)
);

CREATE TABLE accounts
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT         NOT NULL REFERENCES users (id),
    balance  NUMERIC(19, 2) NOT NULL CHECK (balance >= 0)
);

CREATE INDEX idx_accounts_owner_id ON accounts (owner_id);

CREATE TABLE transactions
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id              BIGINT                   NOT NULL REFERENCES accounts (id),
    counterparty_account_id BIGINT                   NOT NULL REFERENCES accounts (id),
    transaction_type        VARCHAR(32)              NOT NULL,
    amount                  NUMERIC(19, 2)           NOT NULL,
    commission              NUMERIC(19, 2)           NOT NULL,
    description             VARCHAR(255),
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_transactions_account_id_created_at ON transactions (account_id, created_at DESC);

